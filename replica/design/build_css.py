"""Generate tokens.css from tokens.json. Run after every token change (and after /replica-brand)."""
import json
t = json.load(open("tokens.json"))
px = lambda n: f"{n}px"

def theme_block(name):
    c = t["color"][name]; s = t["shadow"][name]
    lines = [f"  --{k}: {v};" for k, v in c.items()]
    lines += [f"  --elev-{k}: {v};" for k, v in s.items()]
    # shadcn-vue aliases (its 'accent' means hover surface, ours means brand; so primary = our accent)
    alias = {
      "background":"bg","foreground":"text","card":"surface","card-foreground":"text",
      "popover":"surface-raised","popover-foreground":"text","primary":"accent","primary-foreground":"on-accent",
      "secondary":"surface-hover","secondary-foreground":"text","muted":"surface","muted-foreground":"text-muted",
      "accent":None,"accent-foreground":"text","destructive":"danger-solid","destructive-foreground":"on-danger",
      "border":None,"input":"border-input","ring":"accent",
      "sidebar":"surface","sidebar-foreground":"text","sidebar-primary":"accent","sidebar-primary-foreground":"on-accent",
      "sidebar-accent":"surface-hover","sidebar-accent-foreground":"text","sidebar-border":"border","sidebar-ring":"accent",
    }
    lines.append("  /* shadcn-vue variable names, pointing at our roles */")
    for k, v in alias.items():
        if k == "accent": lines.append(f"  --sc-accent: var(--surface-hover);")
        elif v: lines.append(f"  --sc-{k}: var(--{v});")
    lines.append("  --sc-border: var(--border);")
    return "\n".join(lines)

roles = list(t["color"]["dark"].keys())
out = ["/* GENERATED by build_css.py from tokens.json. Do not edit by hand. */",
       "/* Import once in app/assets/css/main.css after `@import \"tailwindcss\";` */", ""]
out.append("/* .light lets a light island sit inside the dark root (design page, previews). */")
out.append(":root, .light {")
out.append(f"  --font-ui: {t['font']['sans']};")
out.append(f"  --font-code: {t['font']['mono']};")
out.append(f"  --radius: {px(t['radius']['md'])}; /* shadcn-vue base radius */")
for k, v in t["motion"].items():
    if not k.startswith("_"): out.append(f"  --motion-{k}: {v};")
for k, v in t["layout"].items():
    if isinstance(v, int): out.append(f"  --layout-{k}: {px(v)};")
for k, v in t["z"].items(): out.append(f"  --z-{k}: {v};")
out.append("  color-scheme: light;")
out.append(theme_block("light"))
out.append("}")
out.append("")
out.append("/* Dark is the default: @nuxtjs/color-mode with preference 'dark', classSuffix '' puts .dark on <html>. */")
out.append(".dark {\n  color-scheme: dark;\n" + theme_block("dark") + "\n}")
out.append("")
out.append("@custom-variant dark (&:where(.dark, .dark *):not(:where(.light, .light *)));")
out.append("")
out.append("/* Tailwind v4: utilities like bg-surface, text-muted, border-input, ring-accent, bg-primary (shadcn) */")
out.append("@theme inline {")
out.append("  --font-sans: var(--font-ui);\n  --font-mono: var(--font-code);")
for r in roles:
    name = "muted" if r == "text-muted" else r
    out.append(f"  --color-{name}: var(--{r});")
for k in ["background","foreground","card","card-foreground","popover","popover-foreground","primary","primary-foreground",
          "secondary","secondary-foreground","muted-foreground","destructive","destructive-foreground",
          "input","ring","sidebar","sidebar-foreground","sidebar-primary","sidebar-primary-foreground",
          "sidebar-accent","sidebar-accent-foreground","sidebar-border","sidebar-ring"]:
    out.append(f"  --color-{k}: var(--sc-{k});")
out.append("  /* note: --color-accent / --color-border / --color-muted are OUR roles (brand accent, border, muted text).")
out.append("     shadcn components that use bg-accent for hover are switched to bg-surface-hover when generated. */")
for k, v in t["radius"].items(): out.append(f"  --radius-{k}: {px(v)};")
for k in t["shadow"]["dark"]: out.append(f"  --shadow-{k}: var(--elev-{k});")
for size, v in t["type"].items():
    if size == "terminal": continue
    out.append(f"  --text-{size}: {px(v['size'])};\n  --text-{size}--line-height: {px(v['line'])};\n  --text-{size}--font-weight: {v['weight']};")
out.append("  --ease-app: var(--motion-ease);")
out.append("}")
out.append("""
@layer base {
  html, body { background: var(--bg); color: var(--text); font-family: var(--font-ui);
    font-size: 13px; line-height: 20px; -webkit-font-smoothing: antialiased; }
  * { border-color: var(--border); }
  :focus-visible { outline: 2px solid var(--accent); outline-offset: 2px; }
  ::selection { background: color-mix(in srgb, var(--accent) 35%, transparent); }
  @media (prefers-reduced-motion: reduce) {
    *, *::before, *::after { animation-duration: 1ms !important; transition-duration: 1ms !important; }
  }
}""")
open("tokens.css", "w").write("\n".join(out) + "\n")

# xterm.js themes, ready to import
def xterm(name):
    c = t["color"][name]; a = lambda k: c["ansi-" + k]
    return {"background": c["terminal-bg"], "foreground": c["terminal-fg"], "cursor": c["terminal-cursor"],
            "cursorAccent": c["terminal-bg"], "selectionBackground": c["accent"] + "55",
            **{k: a(k) for k in ["black","red","green","yellow","blue","magenta","cyan","white"]},
            **{"bright" + k.capitalize(): a("bright-" + k) for k in ["black","red","green","yellow","blue","magenta","cyan","white"]}}
themes = {"default-dark": xterm("dark"), "default-light": xterm("light")}
# Extra palettes users can pick per host or group (terminal-palettes.json).
names = ["ansi-" + k for k in ["black","red","green","yellow","blue","magenta","cyan","white"]]
labels = {"default-dark": "Dalan dark", "default-light": "Dalan light"}
for key, p in json.load(open("terminal-palettes.json")).items():
    base = ["black","red","green","yellow","blue","magenta","cyan","white"]
    themes[key] = {"background": p["bg"], "foreground": p["fg"], "cursor": p["cursor"], "cursorAccent": p["bg"], "selectionBackground": p["sel"],
        **{k: p["ansi"][i] for i, k in enumerate(base)}, **{"bright" + k.capitalize(): p["ansi"][8 + i] for i, k in enumerate(base)}}
    labels[key] = p["label"]
open("terminal-themes.ts", "w").write("// GENERATED by build_css.py from tokens.json\nimport type { ITheme } from '@xterm/xterm'\n\nexport const terminalThemes: Record<string, ITheme> = "
    + json.dumps(themes, indent=2) + "\n\nexport const terminalThemeLabels: Record<string, string> = " + json.dumps(labels, indent=2) + "\n")
