    async fn mysql_round_trip(port: u16, pw: &str) {
        let conn = my(port, pw, None).await;
        let RawConn::My(c) = &conn else {
            unreachable!()
        };
        for sql in [
            "drop database if exists d16_a", "drop database if exists d16_b", "create database d16_a", "create database d16_b",
            "create table d16_a.customers (id bigint not null auto_increment primary key, email varchar(80) not null, tier varchar(10) default 'basic', unique key uq_email (email))",
            "create table d16_a.orders (id bigint not null primary key, customer_id bigint not null, total decimal(10,2), key by_customer (customer_id), constraint fk_customer foreign key (customer_id) references d16_a.customers (id) on delete cascade, constraint ck_total check (total >= 0))",
            "create view d16_a.big_orders as select id, total from d16_a.orders where total > 100",
            "create function d16_a.twice(x int) returns int deterministic return x * 2",
            "create trigger d16_a.orders_tidy before insert on d16_a.orders for each row set new.total = coalesce(new.total, 0)",
            "create table d16_b.customers (id int not null primary key, email varchar(40), legacy text)",
            "create table d16_b.old_stuff (id int)",
            "create view d16_b.gone as select 1 as x",
        ] {
            c.query(sql, 0).await.unwrap_or_else(|e| panic!("{sql}: {}", e.message));
        }
        let ids = round_trip(&conn, "d16_a", "d16_b").await;
        for want in [
            "table:orders",
            "column:customers.id",
            "column:customers.legacy",
            "table:old_stuff",
            "view:gone",
            "function:twice",
            "trigger:orders.orders_tidy",
        ] {
            assert!(
                ids.iter().any(|i| i == want),
                "{port}: {want} not in {ids:?}"
            );
        }
        c.query("drop database d16_a", 0).await.unwrap();
        c.query("drop database d16_b", 0).await.unwrap();
    }
