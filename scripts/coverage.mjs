// Builds replica/testing/coverage.md: which tests cover which flow (F01 to F12) and screen (S01 to S25), found by
// reading the test sources. Run `pnpm coverage` after adding tests; `pnpm coverage --check` fails when a cell that
// should be filled is empty (what CI runs once T4 is finished).
//
// Where an ID comes from:
//   browser e2e   a flow or screen ID in a test title (`F12: a changed key blocks ...`) in tests/e2e and tests/fake
//   walk          `flow:` and `screen:` of each step in tests/walk/ch*.spec.ts
//   a11y          the screen state ids in tests/a11y/screens.ts (`S18-password`)
//   rust          a flow or screen ID in the doc comment above a Rust test, or in its name
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = process.cwd()
const walk = (dir, ext, skip = ['node_modules', 'target', '.nuxt', '.output', '.output-test']) => readdirSync(join(root, dir)).flatMap((n) => {
  const rel = join(dir, n)
  if (skip.includes(n)) return []
  return statSync(join(root, rel)).isDirectory() ? walk(rel, ext, skip) : n.endsWith(ext) ? [rel] : []
})
const FLOWS = Array.from({ length: 12 }, (_, i) => `F${String(i + 1).padStart(2, '0')}`)
const SCREENS = Array.from({ length: 25 }, (_, i) => `S${String(i + 1).padStart(2, '0')}`)
const ids = text => [...new Set(text.match(/\b[FS]\d{2}\b/g) ?? [])]

/** layer -> id -> test names */
const found = { walk: {}, e2e: {}, a11y: {}, rust: {}, app: {} }
const add = (layer, id, name) => ((found[layer][id] ??= new Set()).add(name))

for (const f of [...walk('tests/e2e', '.spec.ts'), ...walk('tests/fake', '.spec.ts')]) {
  for (const m of readFileSync(join(root, f), 'utf8').matchAll(/\btest(?:\.describe)?\(\s*(['"`])((?:\\.|(?!\1).)*)\1/g)) for (const id of ids(m[2])) add('e2e', id, `${f.split('/').pop()}: ${m[2].slice(0, 70)}`)
}
for (const f of [...walk('tests/app/specs', '.e2e.ts'), 'tests/app/walk.e2e.ts']) {
  const text = readFileSync(join(root, f), 'utf8')
  for (const m of text.matchAll(/\bdescribe\(\s*(['"`])((?:\\.|(?!\1).)*)\1/g)) for (const id of ids(m[2])) add('app', id, `${f.split('/').pop()}: ${m[2].slice(0, 60)}`)
  for (const m of text.matchAll(/flow:\s*'(F\d\d)'/g)) add('app', m[1], `${f.split('/').pop()}`)
  for (const m of text.matchAll(/screen:\s*'(S\d\d)'/g)) add('app', m[1], `${f.split('/').pop()}`)
}
for (const f of walk('tests/walk', '.spec.ts')) {
  for (const m of readFileSync(join(root, f), 'utf8').matchAll(/\{\s*id:\s*'([^']+)'(?:,\s*flow:\s*'(F\d\d)')?(?:,\s*screen:\s*'(S\d\d)')?/g)) {
    if (m[2]) add('walk', m[2], m[1])
    if (m[3]) add('walk', m[3], m[1])
  }
}
for (const m of readFileSync(join(root, 'tests/a11y/screens.ts'), 'utf8').matchAll(/id: '(S\d\d)-([a-z0-9-]+)'/g)) add('a11y', m[1], m[2])
for (const f of walk('src-tauri/src', '.rs')) {
  const lines = readFileSync(join(root, f), 'utf8').split('\n')
  lines.forEach((l, i) => {
    const fn = /^\s*(?:pub(?:\(crate\))?\s+)?(?:async\s+)?fn\s+(\w+)/.exec(l)
    if (!fn) return
    const attrs = lines.slice(Math.max(0, i - 12), i)
    if (!attrs.some(a => /#\[(tokio::)?test/.test(a))) return
    const doc = attrs.filter(a => a.trim().startsWith('///') || a.trim().startsWith('//')).join(' ')
    for (const id of ids(`${fn[1]} ${doc}`)) add('rust', id, `${f.replace('src-tauri/src/', '')}: ${fn[1]}`)
  })
}

const cell = (layer, id) => (found[layer][id]?.size ? String(found[layer][id].size) : '·')
const row = (id, layers) => `| ${id} | ${layers.map(l => cell(l, id)).join(' | ')} |`
const out = []
out.push('# Test coverage', '', 'Generated by `pnpm coverage` from the test sources. Do not edit. A number is how many tests name that flow or screen; `·` means none yet.', '')
out.push('## Flows', '', '| flow | walk | browser | rust | real app |', '|---|---|---|---|---|', ...FLOWS.map(id => row(id, ['walk', 'e2e', 'rust', 'app'])), '')
out.push('## Screens', '', '| screen | walk | browser | a11y states | rust |', '|---|---|---|---|---|', ...SCREENS.map(id => row(id, ['walk', 'e2e', 'a11y', 'rust'])), '')
// Per state: the screen states in tests/a11y/screens.ts, each checked by axe and drawn in dark and light.
const stateIds = [...readFileSync(join(root, 'tests/a11y/screens.ts'), 'utf8').matchAll(/id: '(S\d\d-[a-z0-9-]+)'/g)].map(m => m[1])
const shot = (id, theme) => (existsSync(join(root, `tests/visual/__screenshots__/${id}-${theme}.png`)) ? '✓' : '·')
out.push('## Screen states', '', 'Each state is opened in the browser tests, checked by axe (dark; some in light too), and has a screenshot baseline in dark and light.', '', '| state | axe | picture dark | picture light |', '|---|---|---|---|', ...stateIds.map(id => `| ${id} | ✓ | ${shot(id, 'dark')} | ${shot(id, 'light')} |`), '')
const missingShots = stateIds.filter(id => shot(id, 'dark') === '·' || shot(id, 'light') === '·')

const empty = [
  ...FLOWS.filter(id => !found.walk[id] && !found.e2e[id]).map(id => `${id} has no browser or walk test`),
  ...SCREENS.filter(id => !found.walk[id] && !found.e2e[id] && !found.a11y[id]).map(id => `${id} has no browser, walk or accessibility test`),
  ...missingShots.map(id => `${id} has no screenshot baseline in dark or light`),
]
out.push('## Gaps', '', ...(empty.length ? empty.map(e => `- ${e}`) : ['None.']), '')
writeFileSync(join(root, 'replica/testing/coverage.md'), out.join('\n'))
console.log(`${FLOWS.length} flows, ${SCREENS.length} screens, ${empty.length} gaps. Written to replica/testing/coverage.md`)
if (process.argv.includes('--check') && empty.length) {
  console.error(empty.join('\n'))
  process.exit(1)
}
