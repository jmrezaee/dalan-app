import { expect, test } from '../support/fixtures'
import type { Page } from '@playwright/test'
import { openApp } from './harness'

// D5 of SQL and MongoDB (replica/databases/spec.md): a table's structure and reviewed `alter` changes (S38, F24), the
// plan of a query (S39, F25) and the diagram with export (S40). The fake backend answers (tests/fake/commands/sql.ts).
const nav = (page: Page) => page.getByRole('navigation', { name: 'Vault' })

async function openShop(page: Page, mode: 'Confirm writes' | 'Read-only' = 'Confirm writes') {
  await nav(page).getByRole('link', { name: /Databases/ }).click()
  await page.getByRole('button', { name: 'New database' }).click()
  await page.getByTestId('new-database-dialog').getByRole('button', { name: 'Continue' }).click()
  const s = page.getByTestId('db-form-sheet')
  await s.getByLabel('Name', { exact: true }).fill('app-prod')
  await s.getByLabel('Address').fill('db.internal')
  await s.getByLabel('Database', { exact: true }).fill('app')
  await s.getByLabel('Username').fill('app')
  if (mode === 'Read-only') await s.getByRole('radio', { name: /Read-only/ }).click()
  await s.getByRole('button', { name: 'Save' }).click()
  await expect(s).toHaveCount(0)
  await page.getByRole('row', { name: /app-prod/ }).dblclick()
  const tab = page.getByTestId('sql-tab-app-prod')
  await expect(tab.getByRole('tree', { name: 'Schemas and tables' })).toBeVisible()
  return tab
}
const viewTab = (tab: ReturnType<Page['getByTestId']>, name: RegExp | string) => tab.getByRole('group', { name: 'View' }).getByRole('button', { name })

test.describe('Table structure (S38, F24)', () => {
  test('S38: the structure lists columns with their keys, then indexes, foreign keys and the DDL', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openShop(page)
    await tab.getByTestId('sql-object-orders').click()
    await viewTab(tab, 'Structure').click()
    const s = tab.getByTestId('sql-structure')
    await expect(s.getByTestId('structure-col-id')).toContainText('pk')
    await expect(s.getByTestId('structure-col-customer_id')).toContainText('fk → public.customers(id)')
    await expect(s.locator('[data-part=stats]')).toContainText('1,180 rows')
    await viewTab(tab, /^Indexes/).click()
    await expect(s.getByRole('region', { name: 'Indexes' })).toContainText('orders_pkey')
    await viewTab(tab, /^Foreign keys/).click()
    await expect(s.getByRole('region', { name: 'Foreign keys' })).toContainText('orders_customer_id_fkey')
    await viewTab(tab, 'DDL').click()
    await expect(s.getByTestId('structure-ddl')).toContainText('create table "public"."orders"')
    await viewTab(tab, 'Data').click()
    await expect(tab.getByRole('grid', { name: 'public.orders rows' })).toBeVisible()
  })

  test('F24: a new column and a new index are reviewed as statements, applied, and the structure shows them', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openShop(page)
    await tab.getByTestId('sql-object-no_key').click()
    await viewTab(tab, 'Structure').click()
    await tab.getByLabel('New column name').fill('refunded_qty')
    await tab.getByLabel('New column type').fill('integer')
    await tab.getByLabel('New column default').fill('0')
    await tab.getByRole('button', { name: 'Add column' }).click()
    const pending = tab.getByTestId('structure-pending')
    await expect(pending).toContainText('Add column refunded_qty integer default 0')
    await pending.getByRole('button', { name: 'Review and apply' }).click()
    const d = page.getByTestId('structure-review')
    await expect(d.getByLabel('Statement')).toHaveText('alter table "public"."no_key" add column "refunded_qty" integer default 0;')
    await d.getByRole('button', { name: 'Apply' }).click()
    await expect(d).toHaveCount(0)
    await expect(tab.getByTestId('structure-col-refunded_qty')).toBeVisible()
    await expect(pending).toHaveCount(0)
    // The data view starts again with the new column.
    await viewTab(tab, 'Data').click()
    await expect(tab.getByRole('grid', { name: 'public.no_key rows' }).getByRole('columnheader', { name: /refunded_qty/ })).toBeVisible()
  })

  test('F24: dropping a column and changing a type ask for the database\'s name, with their warnings', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openShop(page)
    await tab.getByTestId('sql-object-no_key').click()
    await viewTab(tab, 'Structure').click()
    await tab.getByRole('button', { name: 'Drop b' }).click()
    await tab.getByRole('button', { name: 'Edit a' }).click()
    await tab.getByLabel('Type of a').fill('bigint')
    await tab.getByRole('button', { name: 'Done' }).click()
    await tab.getByRole('button', { name: 'Review and apply' }).click()
    const d = page.getByTestId('structure-review')
    await expect(d).toContainText('Change no_key on app-prod?')
    await expect(d.locator('[data-part=warnings]')).toContainText('Dropping b deletes everything stored in it.')
    await expect(d.locator('[data-part=warnings]')).toContainText('Changing the type of a locks the table')
    await expect(d.getByRole('button', { name: 'Apply' })).toBeDisabled()
    await d.getByLabel('Type app-prod to confirm').fill('app-prod')
    await d.getByRole('button', { name: 'Apply' }).click()
    await expect(tab.getByTestId('structure-col-b')).toHaveCount(0)
    await expect(tab.getByTestId('structure-col-a')).toContainText('bigint')
  })

  test('S38: a Read-only database shows the structure but offers no changes', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openShop(page, 'Read-only')
    await tab.getByTestId('sql-object-no_key').click()
    await viewTab(tab, 'Structure').click()
    await expect(tab.getByText('This database is read-only in Dalan, so the structure can be read but not changed.')).toBeVisible()
    await expect(tab.getByLabel('New column name')).toHaveCount(0)
    await expect(tab.getByRole('button', { name: 'Drop b' })).toHaveCount(0)
  })
})

test.describe('Explain (S39, F25)', () => {
  async function query(page: Page, tab: ReturnType<Page['getByTestId']>, sql: string) {
    await tab.getByRole('button', { name: 'New query' }).click()
    await tab.getByRole('textbox', { name: /SQL$/ }).click()
    await page.keyboard.insertText(sql)
  }

  test('S39: Explain analyze shows the tree with times, estimate against actual, and a hint whose actions open SQL in a new tab', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openShop(page)
    await query(page, tab, 'select * from orders where status = \'paid\'')
    await tab.getByTestId('sql-explain-analyze').click()
    const plan = tab.getByTestId('sql-plan')
    await expect(plan).toContainText('81 ms total')
    await expect(plan).toContainText('rolled-back transaction')
    await expect(plan.getByTestId('plan-node')).toHaveCount(5)
    await expect(plan.getByTestId('plan-node').nth(2)).toContainText('Seq Scan on orders o')
    await expect(plan.getByTestId('plan-node').nth(2)).toContainText('est 1,200 · got 30,877')
    await expect(plan.getByTestId('plan-hint')).toContainText('statistics look stale')
    await plan.getByRole('button', { name: 'Open an index draft' }).click()
    await expect(tab.getByRole('button', { name: /^Draft/ })).toBeVisible()
    await expect(tab.getByRole('textbox', { name: /SQL$/ })).toContainText('create index on "public"."orders" ("status")')
  })

  test('S39: plain Explain does not run the statement, and Explain analyze of a change is refused', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openShop(page)
    await query(page, tab, 'select * from customers')
    await tab.getByTestId('sql-explain').click()
    await expect(tab.getByTestId('sql-plan')).toContainText('The statement was not run.')
    await expect(tab.getByTestId('sql-plan').getByRole('button', { name: 'Run with timings' })).toBeVisible()
    await tab.getByRole('button', { name: 'Text' }).click()
    await expect(tab.getByTestId('sql-plan').locator('pre')).toContainText('Seq Scan on customers c')
    await tab.getByRole('button', { name: 'New query' }).click()
    await tab.getByRole('textbox', { name: /SQL$/ }).click()
    await page.keyboard.insertText('update customers set name = \'x\' where id = 1')
    await tab.getByTestId('sql-explain-analyze').filter({ visible: true }).click()
    await expect(tab.getByTestId('sql-plan').getByRole('alert')).toContainText('only works for reads')
  })
})

test.describe('Diagram (S40)', () => {
  test('S40: the diagram follows foreign keys the steps asked for, and exports through Rust', async ({ page }) => {
    const fake = await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openShop(page)
    await tab.getByTestId('sql-object-orders').click()
    await tab.getByTestId('sql-new-diagram').click()
    const g = tab.getByTestId('sql-diagram')
    await expect(g.getByTestId('diagram-box-orders')).toBeVisible()
    await expect(g.getByTestId('diagram-box-customers')).toBeVisible()
    await expect(g.getByTestId('diagram-box-order_items')).toBeVisible()
    await expect(g.locator('[data-part=count]')).toContainText('3 of 5 tables')
    await g.getByLabel('Steps').fill('0')
    await g.getByRole('button', { name: 'Draw' }).click()
    await expect(g.getByTestId('diagram-box-customers')).toHaveCount(0)
    await g.getByLabel('Steps').fill('1')
    await g.getByLabel('Keys only').check()
    await g.getByRole('button', { name: 'Draw' }).click()
    await expect(g.getByTestId('diagram-box-orders')).toBeVisible()
    await g.getByRole('button', { name: 'SVG' }).click()
    await expect(g.getByRole('status')).toContainText('Saved /tmp/public.orders-diagram.svg')
    expect((await fake.calls()).some(c => c.startsWith('export:public.orders-diagram.svg:'))).toBe(true)
    await tab.getByRole('button', { name: 'Close Diagram · orders' }).click()
    await expect(g).toHaveCount(0)
  })
})
