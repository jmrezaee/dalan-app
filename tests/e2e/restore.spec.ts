import { expect, test } from '../support/fixtures'
import type { Page } from '@playwright/test'
import { openApp } from './harness'

// D12 (replica/databases/restore-copy.md): S48 "Restore a dump", F31. The fake backend reads no file; it answers
// with a made-up dump for the tab's engine and keeps the gate's rules.
const nav = (page: Page) => page.getByRole('navigation', { name: 'Vault' })

async function openShop(page: Page, opts: { production?: boolean, mode?: RegExp } = {}) {
  await nav(page).getByRole('link', { name: /Databases/ }).click()
  await page.getByRole('button', { name: 'New database' }).click()
  await page.getByTestId('new-database-dialog').getByRole('button', { name: 'Continue' }).click()
  const s = page.getByTestId('db-form-sheet')
  await s.getByLabel('Name', { exact: true }).fill('app-prod')
  if (opts.production) await s.getByRole('radio', { name: 'Production' }).click()
  await s.getByLabel('Address').fill('db.internal')
  await s.getByLabel('Database', { exact: true }).fill('app')
  await s.getByLabel('Username').fill('app')
  if (opts.mode) await s.getByRole('radio', { name: opts.mode }).click()
  await s.getByRole('button', { name: 'Save' }).click()
  await expect(s).toHaveCount(0)
  await page.getByRole('row', { name: /app-prod/ }).dblclick()
  const tab = page.getByTestId('sql-tab-app-prod')
  await expect(tab.getByRole('tree', { name: 'Schemas and tables' })).toBeVisible()
  await tab.getByTestId('sql-open-transfer').click()
  await tab.getByTestId('sql-restore').click()
  return page.getByTestId('restore-dialog')
}

test.describe('Restore a dump (S48, F31)', () => {
  test('a dump from elsewhere: what is inside, the target, a typed review, progress and the result with warnings', async ({ page }) => {
    const fake = await openApp(page, { scenario: 'team', unlocked: true })
    const dlg = await openShop(page)
    await expect(dlg.getByRole('list', { name: 'Steps' }).locator('[aria-current=step]')).toHaveText('1. File')
    await dlg.getByTestId('restore-pick-file').click()
    // What's inside: the source, the objects and what needs attention.
    await expect(dlg.locator('[data-part=source]')).toContainText('PostgreSQL custom archive')
    await expect(dlg.locator('[data-part=source]')).toContainText('pg_dump 16.4')
    await expect(dlg.getByRole('table', { name: 'Objects in the dump' })).toContainText('public.order_count(integer)')
    await expect(dlg.locator('[data-part=notes]')).toContainText('owned by app_owner')
    await dlg.getByRole('button', { name: 'Next' }).click()
    // Target and options: this database by default, stop if anything exists, one transaction.
    await expect(dlg.getByRole('radio', { name: /app \(this database\)/ })).toBeChecked()
    await expect(dlg.getByRole('radio', { name: 'Stop if anything already exists' })).toBeChecked()
    await expect(dlg.getByRole('radio', { name: 'Stop and undo everything (one transaction)' })).toBeChecked()
    await dlg.getByTestId('restore-next').click()
    // Review: an existing database is typed, Cancel has the focus, Restore waits for the exact name.
    const review = dlg.getByTestId('restore-review')
    await expect(review).toContainText('pg_restore (PostgreSQL) 16.4 on db-primary')
    await expect(review).toContainText('Nothing changes: it runs in one transaction.')
    await expect(review.locator('[data-part=skipped]')).toContainText('Ownership and privileges')
    await expect(dlg.getByRole('button', { name: 'Cancel' })).toBeFocused()
    const go = dlg.getByTestId('restore-confirm')
    await expect(go).toBeDisabled()
    await dlg.getByTestId('restore-typed').fill('app-pro')
    await expect(go).toBeDisabled()
    await dlg.getByTestId('restore-typed').fill('app-prod')
    await go.click()
    const result = dlg.getByTestId('restore-result')
    await expect(result.locator('[data-part=outcome]')).toContainText('Restored into app: 12 objects')
    await expect(result.locator('[data-part=warnings]')).toContainText('role "app_owner" does not exist ×214')
    expect((await fake.calls()).includes('restore:app')).toBe(true)
    await dlg.getByRole('button', { name: 'Close' }).last().click()
    await expect(dlg).toHaveCount(0)
  })

  test('a hostile file is shown with the reason and can go no further', async ({ page }) => {
    const fake = await openApp(page, { scenario: 'team', unlocked: true })
    await fake.restoreNext('hostile')
    const dlg = await openShop(page)
    await dlg.getByTestId('restore-pick-file').click()
    await expect(dlg.locator('[data-part=refused]')).toContainText('Line 18,204 has a client command (`\\!`), which runs a program on the host.')
    await expect(dlg.getByRole('button', { name: 'Next' })).toBeDisabled()
  })

  test('clashes block “stop if anything exists”; drop and replace lists what goes', async ({ page }) => {
    const fake = await openApp(page, { scenario: 'team', unlocked: true })
    await fake.restoreNext('clash')
    const dlg = await openShop(page)
    await dlg.getByTestId('restore-pick-file').click()
    await dlg.getByRole('button', { name: 'Next' }).click()
    await dlg.getByTestId('restore-next').click()
    await expect(dlg.locator('[data-part=blocked]')).toContainText('2 of the dump\'s tables already exist in app')
    await expect(dlg.getByTestId('restore-confirm')).toBeDisabled()
    await dlg.getByRole('button', { name: 'Back' }).click()
    await dlg.getByRole('radio', { name: 'Drop and replace what the dump contains' }).check()
    await dlg.getByTestId('restore-next').click()
    await expect(dlg.locator('[data-part=replaces]')).toContainText('public.customers, public.orders')
    // Add rows is data only.
    await dlg.getByRole('button', { name: 'Back' }).click()
    await dlg.getByRole('radio', { name: /Add rows/ }).check()
    await expect(dlg.getByRole('radio', { name: 'Data only', exact: true })).toBeChecked()
    await expect(dlg.getByRole('radio', { name: 'Schema only' })).toBeDisabled()
  })

  test('production: a new database is the default, the database itself needs Open, and a new one is typed too', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const dlg = await openShop(page, { production: true })
    await dlg.getByTestId('restore-pick-file').click()
    await dlg.getByRole('button', { name: 'Next' }).click()
    await expect(dlg.getByRole('radio', { name: 'A new database on the same server' })).toBeChecked()
    await expect(dlg.getByTestId('restore-next')).toBeDisabled()
    await dlg.getByRole('radio', { name: /this database, production/ }).check()
    await expect(dlg).toContainText('needs it switched to Open first')
    await dlg.getByTestId('restore-next').click()
    await expect(dlg.locator('[data-part=error]')).toContainText('is a production database. To restore into it, switch it to Open first')
    await dlg.getByRole('radio', { name: 'A new database on the same server' }).check()
    await dlg.getByTestId('restore-new-name').fill('app_restored')
    await dlg.getByTestId('restore-next').click()
    await expect(dlg.getByTestId('restore-review')).toContainText('app_restored (new)')
    await expect(dlg.getByText('Type app_restored to confirm')).toBeVisible()
  })

  test('Stop during a one-transaction restore: nothing changed, and a new database goes again', async ({ page }) => {
    const fake = await openApp(page, { scenario: 'team', unlocked: true })
    await fake.restoreNext('slow')
    const dlg = await openShop(page)
    await dlg.getByTestId('restore-pick-file').click()
    await dlg.getByRole('button', { name: 'Next' }).click()
    await dlg.getByRole('radio', { name: 'A new database on the same server' }).check()
    await dlg.getByTestId('restore-new-name').fill('scratch')
    await dlg.getByTestId('restore-next').click()
    await dlg.getByTestId('restore-confirm').click()
    const prog = dlg.getByTestId('restore-progress')
    await expect(prog).toContainText('Restoring into scratch')
    await expect(prog).toContainText('rows of public.orders')
    // The dialog can't be closed while the tool runs: Escape does nothing.
    await page.keyboard.press('Escape')
    await expect(prog).toBeVisible()
    await dlg.getByTestId('restore-stop').click()
    const result = dlg.getByTestId('restore-result')
    await expect(result.locator('[data-part=outcome]')).toHaveText('Nothing changed.')
    await expect(result).toContainText('The new database scratch was removed again.')
    expect((await fake.calls()).includes('restore:stopped:scratch')).toBe(true)
  })
})
