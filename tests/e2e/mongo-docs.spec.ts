import { expect, test } from '../support/fixtures'
import type { Page } from '@playwright/test'
import { openApp } from './harness'

// D8 of SQL and MongoDB (S44, F27): a MongoDB tab browses collections, filters, pages, switches views and edits documents
// through the gate. The fake backend serves `shop` (orders: 600 documents, customers: 30, a view).
const nav = (page: Page) => page.getByRole('navigation', { name: 'Vault' })

async function openMongo(page: Page, mode?: 'Read-only') {
  await nav(page).getByRole('link', { name: /Databases/ }).click()
  await page.getByRole('button', { name: 'New database' }).click()
  await page.getByTestId('new-database-dialog').getByRole('radio', { name: /MongoDB/ }).click()
  await page.getByTestId('new-database-dialog').getByRole('button', { name: 'Continue' }).click()
  const s = page.getByTestId('db-form-sheet')
  await s.getByLabel('Name', { exact: true }).fill('docs-prod')
  await s.getByLabel('Members').fill('mongo.internal:27017')
  await s.getByLabel('Username').fill('app')
  if (mode) await s.getByRole('radio', { name: new RegExp(mode) }).click()
  await s.getByRole('button', { name: 'Save' }).click()
  await expect(s).toHaveCount(0)
  await page.getByRole('row', { name: /docs-prod/ }).dblclick()
  const tab = page.getByTestId('mongo-tab-docs-prod')
  await expect(tab.getByRole('tree', { name: 'Databases and collections' })).toBeVisible()
  return tab
}

test.describe('A MongoDB tab (D8)', () => {
  test('opens, names the server, lists collections and pages through orders', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openMongo(page)
    await expect(tab).toContainText('MongoDB 7.0.14')
    await tab.getByTestId('mongo-coll-orders').click()
    await expect(tab.getByTestId('mongo-doc')).toHaveCount(50)
    await expect(tab.getByTestId('mongo-range')).toHaveText('Documents 1–50')
    await tab.getByRole('button', { name: 'Next page' }).click()
    await expect(tab.getByTestId('mongo-range')).toHaveText('Documents 51–100')
    await tab.getByTestId('mongo-count').click()
    await expect(tab.getByTestId('mongo-count')).toContainText('≈ 600 documents (estimate)')
  })

  test('a filter narrows the list, a bad one says what is wrong, and the table and JSON views show the same documents', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openMongo(page)
    await tab.getByTestId('mongo-coll-customers').click()
    await tab.getByTestId('mongo-filter').fill('{"vip": true}')
    await tab.getByTestId('mongo-apply').click()
    await expect(tab.getByTestId('mongo-doc')).toHaveCount(4)
    await tab.getByTestId('mongo-count').click()
    await expect(tab.getByTestId('mongo-count')).toContainText('4 documents')
    await tab.getByRole('group', { name: 'View' }).getByRole('button', { name: 'Table' }).click()
    await expect(tab.getByRole('table', { name: 'Documents as a table' }).getByRole('row')).toHaveCount(5)
    await tab.getByRole('group', { name: 'View' }).getByRole('button', { name: 'JSON' }).click()
    await expect(tab.getByLabel('Documents as JSON')).toContainText('"customer 7"')
    await tab.getByTestId('mongo-filter').fill('{status: 1}')
    await tab.getByTestId('mongo-apply').click()
    await expect(tab.getByTestId('mongo-error')).toContainText('The filter isn\'t valid JSON')
  })

  test('an edit is held and shown, changes nothing until confirmed, and then comes back from the server', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openMongo(page)
    await tab.getByTestId('mongo-coll-customers').click()
    await tab.getByRole('button', { name: 'Edit document 1', exact: true }).click()
    const dlg = page.getByTestId('mongo-editor-dialog')
    await expect(dlg.getByTestId('mongo-editor')).toContainText('$numberInt')
    await dlg.getByTestId('mongo-editor').getByRole('textbox').click()
    await page.keyboard.press('ControlOrMeta+a')
    await page.keyboard.insertText('{"_id": {"$numberInt": "1"}, "name": "renamed", "vip": false}')
    await dlg.getByTestId('mongo-editor-save').click()
    const review = page.getByTestId('mongo-review')
    await expect(review).toContainText('Replace the document with _id 1 in shop.customers.')
    await review.getByRole('button', { name: 'Cancel' }).click()
    await expect(tab.getByTestId('mongo-doc').first()).toContainText('customer 1')
    await dlg.getByTestId('mongo-editor-save').click()
    await page.getByTestId('mongo-confirm').click()
    await expect(tab.getByTestId('mongo-doc').first()).toContainText('renamed')
  })

  test('delete asks first, insert reports a duplicate key in the server\'s words, and a broken document cannot be reviewed', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openMongo(page)
    await tab.getByTestId('mongo-coll-customers').click()
    await tab.getByRole('button', { name: 'Delete document 2', exact: true }).click()
    await expect(page.getByTestId('mongo-review')).toContainText('This can\'t be undone')
    await page.getByTestId('mongo-confirm').click()
    await expect(tab.getByTestId('mongo-doc')).toHaveCount(29)
    await tab.getByTestId('mongo-new-doc').click()
    const dlg = page.getByTestId('mongo-editor-dialog')
    await dlg.getByTestId('mongo-editor').getByRole('textbox').click()
    await page.keyboard.press('ControlOrMeta+a')
    await page.keyboard.insertText('{"_id": 3, "name": "dup"')
    await expect(dlg.getByTestId('mongo-editor-save')).toBeDisabled()
    await page.keyboard.insertText('}')
    await dlg.getByTestId('mongo-editor-save').click()
    await page.getByTestId('mongo-confirm').click()
    await expect(page.getByTestId('mongo-editor-error')).toContainText('E11000 duplicate key')
  })

  test('a projected result can\'t be edited, and unsaved typing survives Escape', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openMongo(page)
    await tab.getByTestId('mongo-coll-customers').click()
    await tab.getByRole('textbox', { name: 'Project' }).fill('{"name": 1}')
    await tab.getByTestId('mongo-apply').click()
    await expect(tab.locator('[data-part="projected"]')).toBeVisible()
    await expect(tab.getByRole('button', { name: 'Edit document 1', exact: true })).toHaveCount(0)
    await tab.getByRole('textbox', { name: 'Project' }).fill('')
    await tab.getByTestId('mongo-apply').click()
    await tab.getByRole('button', { name: 'Edit document 1', exact: true }).click()
    const dlg = page.getByTestId('mongo-editor-dialog')
    await dlg.getByTestId('mongo-editor').getByRole('textbox').click()
    await page.keyboard.insertText('x')
    await page.keyboard.press('Escape')
    await expect(dlg).toBeVisible()
    await dlg.getByRole('button', { name: 'Cancel' }).click()
    await expect(dlg).toHaveCount(0)
  })

  test('a read-only database refuses to hold a change', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openMongo(page, 'Read-only')
    await tab.getByTestId('mongo-coll-customers').click()
    await tab.getByRole('button', { name: 'Delete document 1', exact: true }).click()
    await expect(tab.getByTestId('mongo-error')).toContainText('read-only in Dalan')
    await expect(page.getByTestId('mongo-review')).toHaveCount(0)
  })
})
