  test('Shell (S47): reads answer at once, JavaScript gets the plain message, Up recalls, a dangerous command asks for the name', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await openMongo(page)
    await tab.getByTestId('mongo-open-shell').click()
    const sh = tab.getByTestId('mongo-shell')
    const input = sh.getByTestId('mongo-shell-input')
    await input.fill('use shop')
    await input.press('Enter')
    await expect(sh.getByTestId('mongo-shell-entry').first()).toContainText('switched to db shop')
    await expect(sh.getByRole('form', { name: 'Command' })).toContainText('shop>')
    await input.fill('show collections')
    await input.press('Enter')
    await expect(sh.getByTestId('mongo-shell-entry').nth(1)).toContainText('orders')
    await input.fill('db.customers.find({ "vip": true })')
    await input.press('Enter')
    await expect(sh.getByTestId('mongo-shell-entry').nth(2)).toContainText('customer 7')
    await input.fill('var x = 1')
    await input.press('Enter')
    await expect(sh.getByTestId('mongo-shell-error')).toContainText('single commands, not JavaScript')
    await input.press('ArrowUp')
    await expect(input).toHaveValue('var x = 1')
    await input.press('ArrowUp')
    await expect(input).toHaveValue('db.customers.find({ "vip": true })')
    await input.fill('db.customers.deleteMany({})')
    await input.press('Enter')
    const review = page.getByTestId('mongo-shell-review')
    await expect(review).toContainText('EVERY document')
    await expect(review).toContainText('It matches 30 documents now')
    await expect(page.getByTestId('mongo-shell-confirm')).toBeDisabled()
    await page.getByTestId('mongo-shell-typed').fill('wrong')
    await expect(page.getByTestId('mongo-shell-confirm')).toBeDisabled()
    await page.getByTestId('mongo-shell-typed').fill('docs-prod')
    await page.getByTestId('mongo-shell-confirm').click()
    await expect(review).toHaveCount(0)
    await input.fill('db.customers.find({})')
    await input.press('Enter')
    await expect(sh.getByTestId('mongo-shell-entry').last()).not.toContainText('customer 1')
  })

