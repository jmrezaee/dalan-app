import { expect, test } from '../support/fixtures'
import type { Page } from '@playwright/test'
import { openApp } from './harness'

// D14 (replica/databases/restore-copy.md §9): saved jobs (E1) and masking (E5). The fake moves no rows; it keeps
// jobs and runs in memory and records a run when a copy, restore or backup carrying the job's id ends.
const nav = (page: Page) => page.getByRole('navigation', { name: 'Vault' })

async function addDb(page: Page, name: string, opts: { production?: boolean } = {}) {
  if (await page.getByRole('tab', { name: 'Vault' }).isVisible()) await page.getByRole('tab', { name: 'Vault' }).click()
  await nav(page).getByRole('link', { name: /Databases/ }).click()
  await page.getByRole('button', { name: 'New database' }).click()
  await page.getByTestId('new-database-dialog').getByRole('button', { name: 'Continue' }).click()
  const s = page.getByTestId('db-form-sheet')
  await s.getByLabel('Name', { exact: true }).fill(name)
  if (opts.production) await s.getByRole('radio', { name: 'Production' }).click()
  await s.getByLabel('Address').fill(`${name}.internal`)
  await s.getByLabel('Database', { exact: true }).fill('app')
  await s.getByLabel('Username').fill('app')
  await s.getByRole('button', { name: 'Save' }).click()
  await expect(s).toHaveCount(0)
  await page.getByRole('row', { name: new RegExp(name) }).dblclick()
  const tab = page.getByTestId(`sql-tab-${name}`)
  await expect(tab.getByRole('tree', { name: 'Schemas and tables' })).toBeVisible()
  return tab
}

test.describe('Saved jobs and masking (E1, E5)', () => {
  test('a masked copy is saved as a job, runs again from Jobs through a fresh review, and its run is recorded', async ({ page }) => {
    const fake = await openApp(page, { scenario: 'team', unlocked: true })
    await addDb(page, 'copy-target')
    const src = await addDb(page, 'app-prod', { production: true })
    await src.getByTestId('sql-open-copy').click()
    const copy = src.getByTestId('copy-tab')
    await copy.getByRole('checkbox', { name: 'Copy public.customers' }).check()
    await copy.getByRole('checkbox', { name: 'Into a new database on that server' }).check()
    await copy.getByRole('textbox', { name: 'New database name' }).fill('scratch')
    await copy.getByTestId('copy-review').click()
    // Production data to a non-production target with no masking: a reminder, not a block.
    await expect(copy.getByTestId('copy-plan').locator('[data-part=warnings]')).toContainText('with no masking. Add rules?')
    const masking = copy.getByTestId('copy-masking')
    await expect(masking).toContainText('1 columns look personal')
    await copy.getByTestId('copy-mask-suggested').click()
    await expect(copy.getByTestId('copy-plan').locator('[data-part=warnings]')).toHaveCount(0)
    await masking.getByRole('combobox', { name: 'Masking for public.customers.name' }).selectOption('fake_name')
    // An edit not yet applied: Copy waits, so what runs is what the review shows.
    await expect(copy.getByTestId('copy-run')).toBeDisabled()
    await expect(copy.locator('[data-part=unapplied]')).toContainText('Apply the changes first')
    await masking.getByRole('button', { name: 'Apply changes' }).click()
    await expect(copy.getByTestId('copy-run')).toBeEnabled()
    const sent = JSON.parse((await fake.calls('copy-request')).at(-1)!.slice('copy-request:'.length))
    expect(sent.masks.sort()).toEqual(['customers.email=fake_email', 'customers.name=fake_name'])
    await copy.getByRole('button', { name: 'Save as a job…' }).click()
    await copy.getByRole('textbox', { name: 'Job name' }).fill('Nightly scratch')
    await copy.getByTestId('copy-save-job').click()
    await expect(copy).toContainText('Saved as the job “Nightly scratch”')
    // Jobs: the job is listed; Run opens its tabs and the review asks again (nothing carries over).
    await page.getByRole('tab', { name: 'Vault' }).click()
    await nav(page).getByRole('link', { name: /Jobs/ }).click()
    const row = page.getByTestId('job-Nightly scratch')
    await expect(row).toContainText('1 objects from app-prod to copy-target, masked')
    await expect(row.locator('[data-part=last-run]')).toHaveText('Never run')
    await row.getByTestId('job-run').click()
    const plan = page.getByTestId('sql-tab-app-prod').getByTestId('copy-plan')
    await expect(plan).toContainText('Running a saved job: it asks again')
    await page.getByTestId('sql-tab-app-prod').getByTestId('copy-run').click()
    await expect(page.getByTestId('sql-tab-app-prod').getByTestId('copy-report')).toContainText('Copied into scratch')
    await page.getByRole('tab', { name: 'Vault' }).click()
    await nav(page).getByRole('link', { name: /Jobs/ }).click()
    await expect(row.locator('[data-part=last-run]')).toContainText('ok')
    await row.getByRole('button', { name: 'History' }).click()
    await row.getByText(/^ok ·/).click()
    await expect(row).toContainText('public.customers → public.customers: done')
  })

  test('the copy that is saved as a job, run right away, is the job\'s first run', async ({ page }) => {
    await openApp(page, { scenario: 'team', unlocked: true })
    await addDb(page, 'copy-target')
    const src = await addDb(page, 'app-prod')
    await src.getByTestId('sql-open-copy').click()
    const copy = src.getByTestId('copy-tab')
    await copy.getByRole('checkbox', { name: 'Copy public.customers' }).check()
    await copy.getByRole('checkbox', { name: 'Into a new database on that server' }).check()
    await copy.getByRole('textbox', { name: 'New database name' }).fill('scratch')
    await copy.getByTestId('copy-review').click()
    await copy.getByRole('button', { name: 'Save as a job…' }).click()
    await copy.getByRole('textbox', { name: 'Job name' }).fill('First run')
    await copy.getByTestId('copy-save-job').click()
    await expect(copy).toContainText('Saved as the job “First run”')
    await copy.getByTestId('copy-run').click()
    await expect(copy.getByTestId('copy-report')).toContainText('Copied into scratch')
    await page.getByRole('tab', { name: 'Vault' }).click()
    await nav(page).getByRole('link', { name: /Jobs/ }).click()
    await expect(page.getByTestId('job-First run').locator('[data-part=last-run]')).toContainText('ok')
  })

  test('a restore saved as a job reads its dump again and asks again; a backup job runs into its folder', async ({ page }) => {
    const fake = await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await addDb(page, 'app-prod')
    await tab.getByTestId('sql-open-transfer').click()
    await tab.getByTestId('sql-restore').click()
    const dlg = page.getByTestId('restore-dialog')
    await dlg.getByTestId('restore-pick-file').click()
    await dlg.getByRole('button', { name: 'Next' }).click()
    await dlg.getByRole('radio', { name: 'A new database on the same server' }).check()
    await dlg.getByTestId('restore-new-name').fill('restored')
    await dlg.getByTestId('restore-next').click()
    await dlg.getByRole('button', { name: 'Save as a job…' }).click()
    await dlg.getByRole('textbox', { name: 'Job name' }).fill('Restore last dump')
    await dlg.getByTestId('restore-save-job').click()
    await expect(dlg).toContainText('Saved as the job “Restore last dump”')
    await dlg.getByRole('button', { name: 'Cancel' }).click()
    // The backup: saved as a job (the folder is picked in Rust), then run from Jobs.
    const b = tab.getByTestId('sql-transfer').getByRole('region', { name: 'Backup' })
    await b.getByRole('button', { name: 'Save as a job…' }).click()
    await b.getByRole('textbox', { name: 'Job name' }).fill('Nightly backup')
    await b.getByTestId('backup-save-job').click()
    await expect(b).toContainText('Saved as the job “Nightly backup”')
    await page.getByRole('tab', { name: 'Vault' }).click()
    await nav(page).getByRole('link', { name: /Jobs/ }).click()
    await page.getByTestId('job-Nightly backup').getByTestId('job-run').click()
    await expect(page.getByTestId('sql-tab-app-prod').getByTestId('sql-transfer').locator('[data-part=done]').last()).toContainText('Saved /backups/app-nightly.dump')
    await page.getByRole('tab', { name: 'Vault' }).click()
    await nav(page).getByRole('link', { name: /Jobs/ }).click()
    await page.getByTestId('job-Restore last dump').getByTestId('job-run').click()
    await expect(dlg.getByRole('table', { name: 'Objects in the dump' })).toBeVisible()
    await dlg.getByRole('button', { name: 'Next' }).click()
    await expect(dlg.getByTestId('restore-new-name')).toHaveValue('restored')
    await dlg.getByTestId('restore-next').click()
    await dlg.getByTestId('restore-confirm').click()
    await expect(dlg.getByTestId('restore-result')).toContainText('Restored into restored')
    await dlg.getByRole('button', { name: 'Close' }).first().click()
    await page.getByRole('tab', { name: 'Vault' }).click()
    await nav(page).getByRole('link', { name: /Jobs/ }).click()
    await expect(page.getByTestId('job-Restore last dump').locator('[data-part=last-run]')).toContainText('ok')
    // Delete asks first.
    await page.getByRole('button', { name: 'Delete Nightly backup' }).click()
    await page.getByRole('button', { name: 'Delete job' }).click()
    await expect(page.getByTestId('job-Nightly backup')).toHaveCount(0)
    expect((await fake.calls()).some(c => c.startsWith('job-backup:'))).toBe(true)
  })

  test('an export can mask columns', async ({ page }) => {
    const fake = await openApp(page, { scenario: 'team', unlocked: true })
    const tab = await addDb(page, 'app-prod')
    await tab.getByTestId('sql-open-transfer').click()
    const exp = tab.getByTestId('sql-transfer').getByRole('region', { name: 'Export', exact: true })
    await exp.getByTestId('export-masks').locator('summary').click()
    await exp.getByRole('button', { name: 'Add a rule' }).click()
    await exp.getByRole('textbox', { name: 'Masked column 1' }).fill('name')
    await exp.getByRole('combobox', { name: 'Masking for column 1' }).selectOption('fake_name')
    await exp.getByRole('button', { name: 'Save as…' }).click()
    await expect(exp.locator('[data-part=done]')).toContainText('Saved')
    expect((await fake.calls()).includes('export-mask:name=fake_name')).toBe(true)
  })
})
